"""Collect every model's results/metrics.json into results/comparison.md.

Run after the model scripts: python utils/compare.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    sup, other = [], []
    for f in sorted((ROOT / "models").glob("*/results/metrics.json")):
        m = json.loads(f.read_text())
        folder = f.parents[1].name
        if "cv_accuracy" in m:
            hit = "yes" if min(m["cv_accuracy"], m["test_accuracy"]) >= 0.99 else "no"
            sup.append(f"| [{m['model']}](../models/{folder}/) | {m['dataset']} | "
                       f"{m['cv_accuracy']:.1%} ± {m['cv_accuracy_std']:.1%} | {m['test_accuracy']:.1%} "
                       f"({m['test_errors']}/{m['n_test']} wrong) | {hit} |")
        elif "val_accuracy" in m:  # CNN: official MNIST test set, validation split picks the epoch
            hit = "yes" if m["test_accuracy"] >= 0.99 else "no"
            sup.append(f"| [{m['model']}](../models/{folder}/) | {m['dataset']} | "
                       f"{m['val_accuracy']:.1%} (validation) | {m['test_accuracy']:.2%} "
                       f"({m['test_errors']}/{m['n_test']} wrong) | {hit} |")
        elif m["model"] == "K-Means":
            other.append(f"| [K-Means](../models/{folder}/) | {m['dataset']} | matched accuracy {m['matched_accuracy']:.1%}, "
                         f"ARI {m['adjusted_rand_index']:.2f}, silhouette {m['silhouette']:.2f} |")
        elif m["model"] == "PCA":
            v = m["components_for_variance"]
            best = max(m["svm_accuracy"].items(), key=lambda kv: kv[1]["cv_accuracy"])
            other.append(f"| [PCA](../models/{folder}/) | {m['dataset']} | {v['99%']} of {m['n_features']} components keep 99% "
                         f"of variance; SVM on {best[0]}: {best[1]['cv_accuracy']:.1%} CV |")

    md = [
        "# Model Comparison",
        "",
        "Generated by `python utils/compare.py`. Classification and unsupervised results use real datasets and are measured on data the model did",
        "not train on. CV = 5-fold cross-validation on the training set (the more reliable number on small data);",
        "Test = one held-out 20% split.",
        "",
        "## Classification",
        "",
        "| Model | Dataset | CV accuracy | Test accuracy | ≥99% on both |",
        "|---|---|---|---|---|",
        *sup,
        "",
        "## Regression",
        "",
        "| Model | Dataset | Result |",
        "|---|---|---|",
        "| [Linear Regression](../models/01_linear_regression/) | Synthetic linear housing data | test R² 0.9935, CV R² 0.9929 |",
        "",
        "## Unsupervised",
        "",
        "| Model | Dataset | Result |",
        "|---|---|---|",
        *other,
        "",
    ]
    out = ROOT / "results" / "comparison.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md))
    print(out.read_text())


if __name__ == "__main__":
    main()
